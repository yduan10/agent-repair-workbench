import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";

test("真实 CLI 检查 → SQLite → 只读分析 API → 页面及断网恢复", async ({ page }) => {
  test.skip(process.env.AWB_ANALYSES_E2E !== "1", "Requires a disposable state directory and dedicated API/frontend; never the user's store.");
  expect(process.env.AWB_STATE_DIR).toMatch(/awb-analysis-e2e-[^/]+\/state$/);
  expect(process.env.AWB_API_PORT).not.toBe("8030");
  expect(process.env.PW_PORT).not.toBe("3010");
  expect(existsSync(process.env.AWB_STATE_DIR!)).toBe(false);
  const writes: string[] = [];
  page.on("request", request => { if (request.url().includes("/api/") && request.method() !== "GET") writes.push(request.method()); });
  await page.goto("/workspace/diagnosis");
  await expect(page.getByRole("heading", { name: "第一份分析，从真实执行开始。" })).toBeVisible();
  expect(existsSync(process.env.AWB_STATE_DIR!)).toBe(false);
  const command = (...args: string[]) => execFileSync("uv", ["run", "--frozen", "--project", "..", "agent-workbench", ...args], { encoding: "utf8", timeout: 15000 });
  command("runs", "init");
  const result = JSON.parse(command("analyze", "--case", "output_mismatch", "--intent", "check_only"));
  expect(result.summary.usage.model_calls).toBe(0);
  expect(result.summary.state.outcome).toBe("check_complete");
  await page.getByRole("button", { name: "刷新分析" }).click();
  await page.getByRole("button", { name: `查看分析 ${result.summary.task_id}` }).click();
  const detail = page.getByRole("region", { name: "分析详情" });
  await expect(detail).toContainText("检查完成");
  await expect(detail).toContainText("费用未知");
  await expect(detail).toContainText("未参与");
  await expect(detail).toContainText("尚无隔离执行记录");
  await page.getByText("摘要、证据与恢复说明", { exact: true }).click();
  await expect(detail).toContainText(result.sha256);
  await expect(detail).toContainText("未调用模型");
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "下载分析摘要" }).click();
  const download = await downloadEvent;
  const chunks: Buffer[] = [];
  for await (const chunk of (await download.createReadStream())!) chunks.push(Buffer.from(chunk));
  const exported = JSON.parse(Buffer.concat(chunks).toString("utf8"));
  expect(exported.summary).toEqual(result.summary);
  expect(exported.sha256).toBe(result.sha256);
  await page.context().setOffline(true);
  await page.getByRole("button", { name: "刷新分析" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "自动更新已暂停" })).toBeVisible();
  await page.context().setOffline(false);
  await page.getByRole("button", { name: "重试读取详情" }).click();
  await expect(page.getByRole("region", { name: "分析记录" }).getByRole("alert")).toHaveCount(0);
  await expect(detail).toContainText(result.sha256);
  expect(writes).toEqual([]);
});
